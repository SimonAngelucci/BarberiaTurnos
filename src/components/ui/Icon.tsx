export type IconName = keyof typeof ICONS;

/**
 * Ícono lineal. Decorativo por defecto (aria-hidden); si el ícono es lo único que hay en un botón, el botón lleva su aria-label.
 * Con `label` el ícono mismo se anuncia a los lectores de pantalla.
 */
export function Icon({ name, size = 18, strokeWidth = 1.75, className, label }: { name: IconName; size?: number; strokeWidth?: number; className?: string; label?: string }) {
  const Cmp = ICONS[name];
  return <Cmp width={size} height={size} strokeWidth={strokeWidth} className={`shrink-0 ${className ?? ""}`} aria-hidden={label ? undefined : true} aria-label={label} role={label ? "img" : undefined} focusable="false" />;
}
